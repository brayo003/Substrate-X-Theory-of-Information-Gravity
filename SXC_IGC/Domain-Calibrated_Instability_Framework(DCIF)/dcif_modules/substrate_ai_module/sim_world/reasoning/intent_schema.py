"""
Intent Schema - Data structures for LLM intentions

This module defines the schema for intentions generated by the LLM.
Intentions are NOT executable actions - they are high-level descriptions
of what an entity wants to do, which must be translated into Goal objects.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Mapping
from datetime import datetime, timezone


@dataclass(frozen=True, slots=True)
class Intent:
    """
    High-level intention from LLM.
    
    Intentions are NOT executable actions. They are descriptions like:
    - "I should gather food."
    - "I want to visit the farm."
    - "I need to talk to Mira."
    
    NOT:
    - Move(x=4, y=9)
    - Interact(target=...)
    
    The LLM can optionally provide a structured objective for high-level goal planning.
    """
    intent_id: str
    entity_id: str
    intent: str  # Natural language description of what to do
    reasoning: str  # Why the entity wants to do this
    confidence: float  # LLM's confidence in this intention (0.0 to 1.0)
    possible_target: str | None = None  # Optional target entity reference
    possible_destination: str | None = None  # Optional location reference
    possible_interaction: str | None = None  # Optional interaction type
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    metadata: Mapping[str, Any] = field(default_factory=dict)
    structured_objective: Mapping[str, Any] | None = None  # Optional structured high-level objective from LLM
    
    def __post_init__(self) -> None:
        object.__setattr__(self, "confidence", max(0.0, min(1.0, float(self.confidence))))


@dataclass(frozen=True, slots=True)
class IntentBatch:
    """Batch of intentions for multiple entities."""
    intents: tuple[Intent, ...] = field(default_factory=tuple)
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    metadata: Mapping[str, Any] = field(default_factory=dict)
