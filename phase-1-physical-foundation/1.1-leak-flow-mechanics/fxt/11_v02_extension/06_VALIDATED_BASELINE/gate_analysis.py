#!/usr/bin/env python3
"""Gates 7--9: conventional sensitivity, null, and model-break analyses.

All simulated signals use the already fitted conventional Eq. (1) echo model.
No hypothetical contribution is injected.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from scipy.optimize import least_squares

from spin_echo import echo_phase, gaussian_envelope

HERE = Path(__file__).resolve().parent


def data():
    with (HERE / "digitized" / "figure5_rotating_points.csv").open() as f:
        rows = list(csv.DictReader(f))
    return (np.array([float(x["spin_echo_time_us"]) for x in rows]) * 1e-6,
            np.array([float(x["normalized_contrast"]) for x in rows]),
            np.array([float(x["error_bar"]) for x in rows]))


FIXED_T2_S = 350e-6  # Paper's approximate reported coherence time; not fit from <60 us points.


def model(t, p, f_rot=3330.0, echo=True, t2_s=FIXED_T2_S):
    """Conventional echo signal; p=(Bgauss, rotation-phase, contrast, offset)."""
    b, phase, contrast, offset = p
    gamma = 2802495.0
    if echo:
        spin_phase = echo_phase(t, b, f_rot, gamma, phase)
    else:
        # Conventional free-precession integral: no pi-pulse sign reversal.
        omega = 2*np.pi*f_rot
        spin_phase = 2*np.pi*gamma*b*(np.sin(omega*t + phase)-np.sin(phase))/omega
    return offset + contrast * gaussian_envelope(t, t2_s) * np.cos(spin_phase)


def fit_conventional(t, y, sigma):
    def residual(p):
        return (model(t, p)-y)/sigma
    result = least_squares(residual, x0=[.071, -1.31, .22, .044],
                           bounds=([0, -2*np.pi, -1, -1], [.5, 2*np.pi, 1, 1]),
                           max_nfev=100000)
    return result.x, float(np.sum(result.fun**2))


def main():
    out = HERE / "outputs" / "gate_analysis"; out.mkdir(parents=True, exist_ok=True)
    tau, y, sigma = data()
    best, chi2 = fit_conventional(tau, y, sigma)
    baseline = model(tau, best)

    # Gate 7: fractional one-at-a-time sensitivity around the fitted conventional model.
    names = ["effective_field", "rotation_phase", "readout_contrast", "readout_offset", "T2", "rotation_frequency"]
    fractions = [-0.10, -0.01, 0.01, 0.10]
    rows = []
    for name in names:
        for frac in fractions:
            p = best.copy(); f = 3330.0
            if name == "effective_field": p[0] *= 1+frac
            elif name == "rotation_phase": p[1] += frac*np.pi
            elif name == "readout_contrast": p[2] *= 1+frac
            elif name == "readout_offset": p[3] += frac*0.1
            elif name == "T2":
                # T2 is fixed from the paper in the baseline, then perturbed here.
                change = model(tau, p, f_rot=f, t2_s=FIXED_T2_S*(1+frac)) - baseline
                rows.append({"parameter": name, "perturbation": frac,
                             "max_absolute_contrast_change": float(np.max(np.abs(change))),
                             "rms_contrast_change": float(np.sqrt(np.mean(change**2)))})
                continue
            elif name == "rotation_frequency": f *= 1+frac
            change = model(tau, p, f_rot=f) - baseline
            rows.append({"parameter": name, "perturbation": frac,
                         "max_absolute_contrast_change": float(np.max(np.abs(change))),
                         "rms_contrast_change": float(np.sqrt(np.mean(change**2)))})
    (out / "sensitivity.json").write_text(json.dumps(rows, indent=2)+"\n")
    fig, ax = plt.subplots(figsize=(8,4))
    for name in names:
        r = [v for v in rows if v["parameter"] == name]
        ax.plot([v["perturbation"] for v in r], [v["rms_contrast_change"] for v in r], "o-", label=name)
    ax.set(xlabel="parameter perturbation (defined in output)", ylabel="RMS contrast change")
    ax.legend(fontsize=8); fig.tight_layout(); fig.savefig(out / "sensitivity.png", dpi=180); plt.close(fig)

    # Gate 8: conventional null Monte Carlo. Fit the same conventional model to
    # signals generated by it; look for biased residual means, not a new term.
    rng = np.random.default_rng(20260728)
    residual_means=[]; reduced_chi2=[]
    for _ in range(500):
        simulated = baseline + rng.normal(0, sigma)
        p, c = fit_conventional(tau, simulated, sigma)
        residual_means.append(float(np.mean(simulated-model(tau, p))))
        reduced_chi2.append(c/(len(tau)-4))
    null = {"seed": 20260728, "trials": 500,
            "mean_of_fitted_residual_means": float(np.mean(residual_means)),
            "sd_of_fitted_residual_means": float(np.std(residual_means, ddof=1)),
            "mean_reduced_chi_squared": float(np.mean(reduced_chi2)),
            "false_residual_rule": "No extra residual model is fitted; test is whether conventional fitted residual means are biased."}
    (out / "null_validation.json").write_text(json.dumps(null, indent=2)+"\n")

    # Gate 9: fit deliberately incomplete conventional models and compare chi2.
    # (1) no rotating magnetic projection: B=0; optimize only contrast/offset/T2.
    def no_field(q): return model(tau, [0, 0, q[0], q[1]])
    r0=least_squares(lambda q:(no_field(q)-y)/sigma, [.22,.04], bounds=([-1,-1],[1,1]))
    # (2) keep field but remove echo inversion; optimize all conventional nuisances.
    r1=least_squares(lambda p:(model(tau,p,echo=False)-y)/sigma, best,
                     bounds=([0,-2*np.pi,-1,-1],[.5,2*np.pi,1,1]))
    breaks={"full_conventional_chi_squared": chi2,
            "no_magnetic_projection_chi_squared": float(np.sum(r0.fun**2)),
            "no_echo_toggling_chi_squared": float(np.sum(r1.fun**2)),
            "statement": "Large degradation is expected if the published field-projection or spin-echo feature is removed."}
    (out / "model_break_tests.json").write_text(json.dumps(breaks, indent=2)+"\n")
    print(json.dumps({"best_fit": best.tolist(), "chi2":chi2, "null":null, "breaks":breaks}, indent=2))


if __name__ == "__main__":
    main()
